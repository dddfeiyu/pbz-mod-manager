def hex_to_rgb(value: str) -> tuple[int, int, int]:
    """'#RRGGBB' -> (r, g, b)。给 QPainter / 测试共用。"""
    s = value.lstrip("#")
    if len(s) == 3:
        s = "".join(ch * 2 for ch in s)
    if len(s) != 6:
        raise ValueError(f"不是合法的十六进制颜色：{value!r}")
    return int(s[0:2], 16), int(s[2:4], 16), int(s[4:6], 16)
